"""Triggers -> proposals -> outbox -> apply (only after the user approves) -> baseline.

Deterministic: no model calls. Items that need judgment (turning an error into a written
convention) are marked needs_model=True for the /session-tuner skill or a person.
"""
from __future__ import annotations

import json
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Dict, List, Optional

from . import kinds
from .model import Item
from .paths import ensure_home, load_config
from .project import project_id, slug
from .stats import flag_path, summary
from .store import LocalStore
from .telemetry import Telemetry

MARK_START = "<!-- agent-kb:start (generated by `kb export claude-md`; edit with kb, not by hand) -->"
MARK_END = "<!-- agent-kb:end -->"
BATCH_RULE = ("Batch: put every independent Read/Grep/Glob in ONE response; put every independent Edit/Write in "
              "ONE response, followed by the test command in the same response. Plan in waves only when the "
              "cause or location is unknown; otherwise act directly.")
COMPOUND_RULE = ("Run commands from the project root with relative paths; avoid `cd … &&`, `;` chains and "
                 "`$(...)` — run separate commands or batch them as parallel tool calls.")


def _now() -> datetime:
    return datetime.now(timezone.utc)


def baseline_path(project: str) -> Path:
    return ensure_home() / "baselines" / f"{slug(project)}.json"


def load_baseline(project: str) -> Optional[Dict[str, object]]:
    p = baseline_path(project)
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


# ---------------------------------------------------------------------------- triggers
def evaluate(tele: Telemetry, project: str, cfg: Optional[dict] = None, manual: bool = False) -> Dict[str, object]:
    cfg = cfg or load_config()
    t = cfg["triggers"]
    state = tele.trigger_state(project)
    since = state["last_applied"] if state and state["last_applied"] else None
    s = summary(tele, project, days=int(t["window_days"]), since=since)
    fired: List[Dict[str, object]] = []

    def fire(name: str, value, threshold, note: str) -> None:
        fired.append({"name": name, "value": value, "threshold": threshold, "note": note})

    top_prefix = s["allow_candidates"][0]["count"] if s["allow_candidates"] else 0
    if s["denied"] >= t["denied_total"] or top_prefix >= t["denied_same_prefix"]:
        fire("denied", s["denied"], t["denied_total"], "lệnh bị chặn hoặc phải duyệt tay")
    rep = [e for e in s["repeated_errors"]
           if e["count"] >= t["repeated_error"] and e["sessions"] >= t["repeated_error_sessions"]]
    if rep:
        fire("repeated_errors", len(rep), t["repeated_error"], "lỗi lặp lại qua nhiều session")
    bad_tools = [x for x in s["tool_errors"] if x["calls"] >= t["tool_error_min_calls"] and x["rate"] > t["tool_error_rate"]]
    if bad_tools:
        fire("tool_error_rate", [x["tool"] for x in bad_tools], t["tool_error_rate"], "tool có tỉ lệ lỗi cao")
    if s["single_read_ratio"] is not None and s["single_read_ratio"] > t["single_read_ratio"]:
        fire("unbatched_reads", s["single_read_ratio"], t["single_read_ratio"], "nhiều lượt chỉ đọc 1 file")
    base = load_baseline(project)
    fc = s["first_ctx_median"]
    if fc and (fc > t["fixed_context_tokens"] or
               (base and base.get("first_ctx_median") and fc > base["first_ctx_median"] * (1 + t["fixed_context_growth"]))):
        fire("fixed_context", fc, t["fixed_context_tokens"], "context cố định lớn")
    share = s["browser"]["output_share"]
    if share is not None and share > t["browser_output_share"]:
        fire("browser_output", share, t["browser_output_share"], "output browser chiếm nhiều token")
    if base:
        worse = [k for k in ("api_calls_median", "ctx_tokens_median", "errors", "denied")
                 if base.get(k) and s.get(k) and s[k] > base[k] * 1.2]
        if worse:
            fire("regression", worse, "baseline +20%", "chỉ số xấu hơn baseline")

    eligible, reason = True, ""
    if manual:                      # the user asked: report, never block
        if s["sessions"] < t["min_sessions"]:
            reason = f"chỉ có {s['sessions']} session, kết quả còn nhiễu"
        return {"project": project, "eligible": True, "reason": reason, "fired": fired, "summary": s}
    if s["sessions"] < t["min_sessions"]:
        eligible, reason = False, f"mới có {s['sessions']}/{t['min_sessions']} session kể từ lần tối ưu trước"
    elif state and state["last_fired"]:
        last = datetime.fromisoformat(state["last_fired"])
        if _now() - last < timedelta(days=int(t["cooldown_days"])):
            eligible, reason = False, f"đang trong thời gian chờ {t['cooldown_days']} ngày"
    return {"project": project, "eligible": eligible, "reason": reason, "fired": fired, "summary": s}


def refresh_flag(tele: Telemetry, project: str) -> Dict[str, object]:
    ev = evaluate(tele, project)
    prev = {}
    fp = flag_path(project)
    if fp.exists():
        try:
            prev = json.loads(fp.read_text(encoding="utf-8"))
        except ValueError:
            prev = {}
    fired = ev["fired"] if ev["eligible"] else prev.get("fired", [])
    flag = {"project": project, "fired": fired, "checked": _now().isoformat()}
    fp.write_text(json.dumps(flag, ensure_ascii=False), encoding="utf-8")
    if ev["eligible"] and ev["fired"] and not prev.get("fired"):   # cooldown starts when a warning first appears
        tele.set_trigger_state(project, last_fired=_now().isoformat())
        if load_config()["triggers"].get("mode") == "background":  # draft proposals now (deterministic, 0 tokens)
            from .store import LocalStore
            props = proposals(ev["summary"], export_claude_md(LocalStore(), project))
            if props:
                flag["outbox"] = str(write_outbox(project, ev, props))
                fp.write_text(json.dumps(flag, ensure_ascii=False), encoding="utf-8")
    return flag


# ---------------------------------------------------------------------------- proposals
def proposals(s: Dict[str, object], existing_guidance: str = "") -> List[Dict[str, object]]:
    out: List[Dict[str, object]] = []
    for a in s["allow_candidates"]:
        if a["risk"] == "never" or a["count"] < 2:
            continue
        out.append({"type": "allow", "rule": a["rule"], "risk": a["risk"], "evidence": a["count"],
                    "needs_confirm": a["risk"] == "review"})
    if s["denied"] and s["denied_compound"] / max(s["denied"], 1) >= 0.5 and COMPOUND_RULE not in existing_guidance:
        out.append({"type": "guidance", "subject": "shell-compound", "text": COMPOUND_RULE,
                    "evidence": f"{s['denied_compound']}/{s['denied']} lệnh bị chặn là lệnh ghép"})
    if s["single_read_ratio"] and s["single_read_ratio"] > 0.25 and BATCH_RULE not in existing_guidance:
        out.append({"type": "guidance", "subject": "batching", "text": BATCH_RULE,
                    "evidence": f"{s['single_read_ratio']:.0%} lượt chỉ đọc 1 file"})
    if s["test_commands"]:
        from .shellparse import TEST_HINT, split_segments
        raw = s["test_commands"][0][0]
        segs = [seg for seg in split_segments(re.sub(r"\d*>&\d+", " ", raw)) if TEST_HINT.search(seg)]
        cmd = re.sub(r"\s+", " ", segs[0]).strip() if segs else ""
        if cmd and cmd not in existing_guidance:
            out.append({"type": "guidance", "subject": "test-command", "text": f"Run tests: `{cmd}`",
                        "evidence": f"chạy thành công {s['test_commands'][0][1]} lần"})
    for e in s["repeated_errors"][:5]:
        if e["count"] >= 2:
            out.append({"type": "error_convention", "signature": e["signature"], "evidence": e["count"],
                        "needs_model": True})
    for f, n in s["reread_files"][:5]:
        out.append({"type": "module_map", "file": f, "evidence": n, "needs_model": True})
    if s["first_ctx_median"] and s["first_ctx_median"] > 25000:
        out.append({"type": "context", "evidence": s["first_ctx_median"],
                    "text": "Context lượt đầu lớn: xem lại MCP server, plugin, skill không dùng cho project này."})
    if s["browser"]["output_share"] and s["browser"]["output_share"] > 0.4:
        out.append({"type": "browser", "evidence": s["browser"]["output_share"],
                    "text": "Output browser chiếm nhiều token: ưu tiên find/get_page_text thay screenshot, "
                            "giao thăm dò cho subagent, ghi tri thức trang vào kb."})
    for i, p in enumerate(out, 1):
        p["n"] = i
    return out


def write_outbox(project: str, ev: Dict[str, object], props: List[Dict[str, object]]) -> Path:
    stamp = _now().strftime("%Y%m%d-%H%M%S")
    path = ensure_home() / "outbox" / f"{slug(project)}-{stamp}.json"
    path.write_text(json.dumps({"id": path.stem, "project": project, "created": _now().isoformat(),
                                "fired": ev["fired"], "proposals": props, "summary": ev["summary"]},
                               ensure_ascii=False, indent=2), encoding="utf-8")
    return path


def list_outbox(project: Optional[str] = None) -> List[Dict[str, object]]:
    out = []
    for f in sorted((ensure_home() / "outbox").glob("*.json"), reverse=True):
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
        except ValueError:
            continue
        if "proposals" in d and (not project or d.get("project") == project):
            d["path"] = str(f)
            out.append(d)
    return out


# ---------------------------------------------------------------------------- apply + export
def export_claude_md(store: LocalStore, project: str) -> str:
    store.reconcile()
    items = [i for i in store.find(project=[project, "global"], kind=kinds.delivered(),
                                   status="active")]
    items.sort(key=lambda i: (i.kind, i.subject_key))
    lines = [MARK_START, "# Project notes (agent-kb)"]
    lines += [f"- {i.body.strip()}" for i in items if i.body.strip()]
    lines.append("- Project memory: as your FIRST action, run only `kb context \"<key words copied from the request, in "
                 "its language>\"` (no other tool in that response), read the answer, then plan. It lists files, tests, "
                 "errors, app pages and the accounts that reached them, from related past sessions (unverified; check "
                 "them). `kb search \"<topic>\"` finds recorded conventions.")
    if store.find_meta(project=project, kind="page", status="active"):
        lines.append("- Before browser work: `kb browser path \"<target page>\" --from <current url>` gives a known "
                     "route; `kb browser page \"<page>\"` shows what is known about a page. Explore only when unknown.")
    lines.append(MARK_END)
    return "\n".join(lines) + "\n"


def write_managed_block(path: Path, block: str) -> None:
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    if MARK_START.split(" (")[0] in text and MARK_END in text:
        start = text.index(MARK_START.split(" (")[0])
        end = text.index(MARK_END) + len(MARK_END)
        text = text[:start] + block.rstrip("\n") + text[end:]
    else:
        text = (text.rstrip("\n") + "\n\n" if text.strip() else "") + block
    path.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")


def apply(outbox_file: Path, project_dir: str, select: Optional[List[int]] = None, target: str = "local",
          include_review: bool = False) -> Dict[str, object]:
    data = json.loads(outbox_file.read_text(encoding="utf-8"))
    project = data["project"]
    if project != project_id(project_dir):
        raise ValueError(f"outbox is for {project}, but {project_dir} is {project_id(project_dir)}")
    chosen = [p for p in data["proposals"] if (select is None or p["n"] in select)]
    store = LocalStore()
    rules, guidance = [], []
    for p in chosen:
        if p["type"] == "allow" and (not p.get("needs_confirm") or include_review or select is not None):
            rules.append(p["rule"])
        elif p["type"] == "guidance":
            item = Item(kind="guidance", project=project, subject_key=p["subject"], title=p["subject"],
                        body=p["text"], rank=1, source={"name": "manual", "via": "kb tune", "outbox": data["id"]})
            guidance.append(store.put(item, actor="kb tune"))
    settings_written = None
    if rules:
        sp = Path(project_dir) / ".claude" / ("settings.local.json" if target == "local" else "settings.json")
        sp.parent.mkdir(parents=True, exist_ok=True)
        cur = json.loads(sp.read_text(encoding="utf-8") or "{}") if sp.exists() else {}
        allow = cur.setdefault("permissions", {}).setdefault("allow", [])
        for r in rules:
            if r not in allow:
                allow.append(r)
        sp.write_text(json.dumps(cur, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        settings_written = str(sp)
    md = Path(project_dir) / "CLAUDE.md"
    write_managed_block(md, export_claude_md(store, project))
    tele = Telemetry()
    flag_path(project).write_text(json.dumps({"project": project, "fired": [], "checked": _now().isoformat()}),
                                  encoding="utf-8")
    baseline_path(project).write_text(json.dumps(dict(data["summary"], applied=_now().isoformat()),
                                                 ensure_ascii=False, indent=2), encoding="utf-8")
    tele.set_trigger_state(project, last_applied=_now().isoformat(), sessions_at_apply=data["summary"]["sessions"])
    applied = Path(str(outbox_file).replace(".json", ".applied.json"))
    outbox_file.rename(applied)
    return {"rules": rules, "guidance": guidance, "settings": settings_written, "claude_md": str(md),
            "baseline": str(baseline_path(project))}
