def module_text(pkg, mod, entity, fields, rule):
    cols = ", ".join(f"{f} TEXT" for f in fields)
    placeholders = ",".join("?" * len(fields))
    names = ", ".join(fields)
    return (f"{HEADER}\"\"\"{pkg.replace('_', ' ').title()}: {entity.replace('_', ' ')} records.\"\"\"\n\n"
            f"TABLE = \"{entity}\"\nFIELDS = {tuple(fields)!r}\n\n\n"
            f"def ensure_table(conn):\n    conn.execute(\"CREATE TABLE IF NOT EXISTS {entity} (id INTEGER PRIMARY KEY, {cols})\")\n\n\n"
            f"def create(conn, {', '.join(fields)}):\n    ensure_table(conn)\n"
            f"    cur = conn.execute(\"INSERT INTO {entity}({names}) VALUES ({placeholders})\", ({', '.join(fields)},))\n"
            f"    conn.commit()\n    return cur.lastrowid\n\n\n"
            f"def get(conn, row_id):\n    ensure_table(conn)\n"
            f"    return conn.execute(\"SELECT * FROM {entity} WHERE id=?\", (row_id,)).fetchone()\n\n\n"
            f"def list_all(conn, limit=100):\n    ensure_table(conn)\n"
            f"    return conn.execute(\"SELECT * FROM {entity} ORDER BY id LIMIT ?\", (limit,)).fetchall()\n\n\n"
            f"def update(conn, row_id, **changes):\n    ensure_table(conn)\n"
            f"    bad = set(changes) - set(FIELDS)\n    if bad:\n        raise ValueError(f\"unknown fields {{sorted(bad)}}\")\n"
            f"    for k, v in changes.items():\n        conn.execute(f\"UPDATE {entity} SET {{k}}=? WHERE id=?\", (v, row_id))\n"
            f"    conn.commit()\n\n\n"
            f"def delete(conn, row_id):\n    ensure_table(conn)\n    conn.execute(\"DELETE FROM {entity} WHERE id=?\", (row_id,))\n    conn.commit()\n\n\n"
            f"{RULES[rule]}")


def main():
    n = 0
    for pkg, mods in DOMAINS.items():
        d = ROOT / pkg
        d.mkdir(exist_ok=True)
        if not (d / "__init__.py").exists():
            (d / "__init__.py").write_text("", encoding="utf-8")
        for mod, entity, fields, rule in mods:
            (d / f"{mod}.py").write_text(module_text(pkg, mod, entity, fields, rule), encoding="utf-8")
            n += 1
    print(f"wrote {n} modules")


if __name__ == "__main__":
    main()
